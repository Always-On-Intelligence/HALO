"""Write README.md for every case that has no hand-written one.

A generated README describes the work from case.yaml and shows its read-mode votes from
results/read/votes.json. Hand-written READMEs (cases with run mode) are left alone; they are the
ones without the marker line below.

Usage: python scripts/make_case_readmes.py [--no-code-only]
"""
import json, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
MARK = '<!-- generated by scripts/make_case_readmes.py -->'
CHANNELS = ('S->M', 'M->A', 'A->S', 'M->S', 'A->M')
STEPS = ('record', 'outcome', 'attribution', 'revision', 'later_use')
ARROW = {c: c.replace('->', '→') for c in CHANNELS}

votes = {}
vf = ROOT / 'results' / 'read' / 'votes.json'
if vf.exists():
    v = json.loads(vf.read_text())
    votes, agents = v['variants'], v['agents']
else:
    agents = []

for d in sorted((ROOT / 'cases').iterdir()):
    f = d / 'case.yaml'
    if not f.exists():
        continue
    readme = d / 'README.md'
    if readme.exists() and MARK not in readme.read_text():
        continue
    c = yaml.safe_load(f.read_text())
    if '--no-code-only' in sys.argv and (c.get('code') or {}).get('repo'):
        continue
    lines = [MARK, f'# {c["name"]}', '',
             f'- **Domain:** {c.get("domain")}', f'- **Kind:** {c.get("kind")}']
    if c.get('report'):
        lines.append(f'- **Report:** {c["report"]}')
    code = c.get('code') or {}
    if code.get('repo'):
        lines.append(f'- **Code:** {code["repo"]}' + (f' at `{code["commit"][:7]}`' if code.get('commit') else ''))
    else:
        lines.append('- **Code:** no public code, so this work has read mode only.')
    lines += ['', '## Sources read in read mode', '']
    lines += [f'- {s["url"]}' + (f' (version {s["version"]})' if s.get('version') else '') for s in c.get('sources', [])]
    lines += ['', '## Configurations reviewed', '']
    for var in c['variants']:
        lines.append(f'- `{var["id"]}`: {var["configuration"]}')
    if any(var['id'] in votes for var in c['variants']):
        lines += ['', '## Read-mode result', '',
                  (f'Majority vote of {len(agents)} oversight agents ({", ".join(agents)}). ' if len(agents) >= 3 else
                   f'Labels from {len(agents)} of the 3 oversight agents so far ({", ".join(agents)}); '
                   'the majority vote is taken once all three have reviewed. ') +
                  'Each review, with quotes and locators, is in `results/read/reviews/`.', '',
                  '| Configuration | ' + ' | '.join(ARROW[x] for x in CHANNELS) + ' | Rec. | Out. | Attr. | Rev. | Use. |',
                  '|---|' + '---|' * 10]
        for var in c['variants']:
            r = votes.get(var['id'])
            if not r:
                continue
            ch = [r['channels'][x]['label'] or 'missing' for x in CHANNELS]
            st = ['stated' if r['steps'][x]['label'] == 'stated' else '·' for x in STEPS]
            lines.append(f'| {var["id"]} | ' + ' | '.join(ch) + ' | ' + ' | '.join(st) + ' |')
    if not (d / 'adapter.py').exists():
        lines += ['', '## Run mode', '',
                  'Not available: run mode executes a work\'s released code, and this work has none.'
                  if not code.get('repo') else
                  'Not yet integrated. See `docs/adding_a_case.md` to add an adapter.']
    readme.write_text('\n'.join(lines) + '\n')
    print('wrote', readme.relative_to(ROOT))
